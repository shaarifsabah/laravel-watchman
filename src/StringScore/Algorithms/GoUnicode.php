    public static function isAscii(string $s): bool
    {
        return !preg_match('/[\x80-\xFF]/', $s);
    }

    /**
     * Decodes $s exactly like Go's []rune(s).
     *
     * @return list<int>
     */
    public static function runes(string $s): array
    {
        if ($s === '') {
            return [];
        }
        $bytes = array_values(unpack('C*', $s));
        if (self::isAscii($s)) {
            return $bytes;
        }
        $n = count($bytes);
        $out = [];
        $i = 0;
        while ($i < $n) {
            $c0 = $bytes[$i];
            if ($c0 < 0x80) {
                $out[] = $c0;
                $i++;
                continue;
            }
            // Accept ranges for the second byte, per Go's utf8 "first" table.
            if ($c0 >= 0xC2 && $c0 <= 0xDF) {
                $size = 2;
                $lo = 0x80;
                $hi = 0xBF;
            } elseif ($c0 >= 0xE0 && $c0 <= 0xEF) {
                $size = 3;
                $lo = $c0 === 0xE0 ? 0xA0 : 0x80;
                $hi = $c0 === 0xED ? 0x9F : 0xBF;
            } elseif ($c0 >= 0xF0 && $c0 <= 0xF4) {
                $size = 4;
                $lo = $c0 === 0xF0 ? 0x90 : 0x80;
                $hi = $c0 === 0xF4 ? 0x8F : 0xBF;
            } else {
                $out[] = self::RUNE_ERROR;
                $i++;
                continue;
            }
            if ($i + $size > $n) {
                $out[] = self::RUNE_ERROR;
                $i++;
                continue;
            }
            $c1 = $bytes[$i + 1];
            if ($c1 < $lo || $c1 > $hi) {
                $out[] = self::RUNE_ERROR;
                $i++;
                continue;
            }
            if ($size === 2) {
                $out[] = (($c0 & 0x1F) << 6) | ($c1 & 0x3F);
                $i += 2;
                continue;
            }
            $c2 = $bytes[$i + 2];
            if ($c2 < 0x80 || $c2 > 0xBF) {
                $out[] = self::RUNE_ERROR;
                $i++;
                continue;
            }
            if ($size === 3) {
                $out[] = (($c0 & 0x0F) << 12) | (($c1 & 0x3F) << 6) | ($c2 & 0x3F);
                $i += 3;
                continue;
            }
            $c3 = $bytes[$i + 3];
            if ($c3 < 0x80 || $c3 > 0xBF) {
                $out[] = self::RUNE_ERROR;
                $i++;
                continue;
            }
            $out[] = (($c0 & 0x07) << 18) | (($c1 & 0x3F) << 12) | (($c2 & 0x3F) << 6) | ($c3 & 0x3F);
            $i += 4;
        }

        return $out;
    }

    /** UTF-8 encodes one valid rune (Go utf8.AppendRune for valid input). */
    public static function chr(int $r): string
    {
        if ($r < 0x80) {
            return \chr($r);
        }
        if ($r < 0x800) {
            return \chr(0xC0 | ($r >> 6)) . \chr(0x80 | ($r & 0x3F));
        }
        if ($r < 0x10000) {
            return \chr(0xE0 | ($r >> 12)) . \chr(0x80 | (($r >> 6) & 0x3F)) . \chr(0x80 | ($r & 0x3F));
        }

        return \chr(0xF0 | ($r >> 18)) . \chr(0x80 | (($r >> 12) & 0x3F))
            . \chr(0x80 | (($r >> 6) & 0x3F)) . \chr(0x80 | ($r & 0x3F));
    }

    /** @param list<int> $runes */
    public static function implode(array $runes): string
    {
        $s = '';
        foreach ($runes as $r) {
            $s .= self::chr($r);
        }

        return $s;
    }

    /** Go unicode.ToUpper. */
    public static function toUpper(int $r): int
    {
        if ($r < 0x80) {
            return ($r >= 0x61 && $r <= 0x7A) ? $r - 32 : $r;
        }

        return self::$upperCache[$r] ??= self::to(0, $r);
    }

    /** Go unicode.ToLower. */
    public static function toLower(int $r): int
    {
        if ($r < 0x80) {
            return ($r >= 0x41 && $r <= 0x5A) ? $r + 32 : $r;
        }

        return self::$lowerCache[$r] ??= self::to(1, $r);
    }

    /** Go unicode.IsLetter. */
    public static function isLetter(int $r): bool
    {
        if ($r < 0x80) {
            return ($r >= 0x41 && $r <= 0x5A) || ($r >= 0x61 && $r <= 0x7A);
        }
        if (isset(self::$letterCache[$r])) {
            return self::$letterCache[$r];
        }
        $lo = 0;
        $hi = intdiv(count(self::LETTER), 2);
        $found = false;
        while ($lo < $hi) {
            $m = ($lo + $hi) >> 1;
            if ($r < self::LETTER[2 * $m]) {
                $hi = $m;
            } elseif ($r > self::LETTER[2 * $m + 1]) {
                $lo = $m + 1;
            } else {
                $found = true;
                break;
            }
        }

        return self::$letterCache[$r] = $found;
    }

    /** Go unicode.to(); $case 0 = UpperCase, 1 = LowerCase. */
    private static function to(int $case, int $r): int
    {
        $lo = 0;
        $hi = intdiv(count(self::CASE_RANGES), 4);
        while ($lo < $hi) {
            $m = ($lo + $hi) >> 1;
            $crLo = self::CASE_RANGES[4 * $m];
            if ($crLo <= $r && $r <= self::CASE_RANGES[4 * $m + 1]) {
                $delta = self::CASE_RANGES[4 * $m + 2 + $case];
                if ($delta >= self::UPPER_LOWER) {
                    return $crLo + ((($r - $crLo) & ~1) | ($case & 1));
                }

                return $r + $delta;
            }
            if ($r < $crLo) {
                $hi = $m;
            } else {
                $lo = $m + 1;
            }
        }

        return $r;
    }
