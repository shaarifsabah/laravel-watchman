<?php

/**
 * Regenerates resources/data/*.php from the upstream Go dependencies that
 * Watchman pins (bbalet/stopwords, abadojack/whatlanggo, dongri/phonenumber,
 * moov-io/iso3166) and the Mozilla Public Suffix List.
 *
 * Usage:
 *   php bin/generate-data.php <go-dump.json> <bbalet-stopwords-dir> <watchman-union_stopwords.go> <public_suffix_list.dat>
 *
 * go-dump.json is produced by a small Go program that marshals
 * whatlanggo's language profiles, phonenumber.GetISO3166() and the
 * iso3166 alpha2/alpha3 tables (see bin/datagen/main.go).
 */

[$self, $dump, $bbalet, $union, $psl] = $argv + [null, null, null, null, null];
if (!$dump || !$bbalet || !$union || !$psl) {
    fwrite(STDERR, "usage: php bin/generate-data.php <go-dump.json> <bbalet-dir> <union_stopwords.go> <public_suffix_list.dat>\n");
    exit(1);
}
$out = __DIR__ . '/../resources/data';
// Where each table comes from (license texts are in licenses/, see NOTICE).
$sources = [
    'whatlanggo.php' => 'github.com/abadojack/whatlanggo v1.0.1 (MIT)',
    'stopwords.php' => 'github.com/bbalet/stopwords v1.0.0 (BSD)',
    'stopwords_union.php' => 'moov-io/watchman internal/prepare/union_stopwords.go (Apache-2.0)',
    'phone.php' => 'github.com/dongri/phonenumber v0.1.13 (MIT)',
    'iso3166.php' => 'github.com/moov-io/iso3166 v0.4.0 (Apache-2.0)',
    'public_suffix.php' => 'Public Suffix List, https://publicsuffix.org/list/public_suffix_list.dat (MPL-2.0)',
];
$write = static function (string $file, $data) use ($out, $sources): void {
    $header = "<?php\n\n// Generated by bin/generate-data.php. DO NOT EDIT.\n// Source: " . ($sources[$file] ?? 'see NOTICE') . "\n\nreturn ";
    file_put_contents("$out/$file", $header . var_export($data, true) . ";\n");
    echo "wrote $file\n";
};

$d = json_decode(file_get_contents($dump), true, 512, JSON_THROW_ON_ERROR);

// --- whatlanggo -------------------------------------------------------------
$langs = [];
foreach ($d['langs'] as $l) {
    $langs[$l['iso6393']] = $l['iso6391'];
}
$write('whatlanggo.php', ['langs' => $langs, 'profiles' => $d['profiles']]);

// --- phone numbers (dongri/phonenumber) ---------------------------------------
$phone = [];
foreach ($d['phone'] as $p) {
    $phone[] = [
        'a2' => $p['Alpha2'], 'a3' => $p['Alpha3'], 'cc' => $p['CountryCode'], 'name' => $p['CountryName'],
        'mobile' => $p['MobileBeginWith'] ?? [], 'lengths' => $p['PhoneNumberLengths'] ?? [],
    ];
}
$write('phone.php', $phone);

// --- iso3166 ----------------------------------------------------------------
$a2 = $d['iso_alpha2'];
ksort($a2);
$a3 = $d['iso_alpha3'];
ksort($a3);
$write('iso3166.php', ['alpha2' => $a2, 'alpha3' => $a3]);

// --- stopwords (bbalet/stopwords) -------------------------------------------
$files = [
    'ar' => 'arabic', 'bg' => 'bulgarian', 'cs' => 'czech', 'da' => 'danish', 'de' => 'german', 'el' => 'greek',
    'en' => 'english', 'es' => 'spanish', 'fa' => 'persian', 'fr' => 'french', 'fi' => 'finnish', 'hu' => 'hungarian',
    'id' => 'indonesian', 'it' => 'italian', 'ja' => 'japanese', 'km' => 'khmer', 'lv' => 'latvian', 'nl' => 'dutch',
    'no' => 'norwegian', 'pl' => 'polish', 'pt' => 'portuguese', 'ro' => 'romanian', 'ru' => 'russian', 'sk' => 'slovak',
    'sv' => 'swedish', 'th' => 'thai', 'tr' => 'turkish',
];
$sources = '';
foreach (glob("$bbalet/stopwords_*.go") as $f) {
    if (!str_ends_with($f, '_test.go')) {
        $sources .= file_get_contents($f) . "\n";
    }
}
$stop = [];
foreach ($files as $code => $var) {
    if (!preg_match('/var ' . $var . ' = map\[string\]string\{(.*?)\}\s*(?:\n|$)/s', $sources, $m)) {
        throw new RuntimeException("missing $var");
    }
    preg_match_all('/"((?:[^"\\\\]|\\\\.)*)"\s*:\s*""/u', $m[1], $words);
    $set = [];
    foreach ($words[1] as $w) {
        $set[stripcslashes($w)] = true;
    }
    $stop[$code] = $set;
}
$write('stopwords.php', $stop);

preg_match_all('/^\t"((?:[^"\\\\]|\\\\.)*)",$/mu', file_get_contents($union), $u);
$unionSet = [];
foreach ($u[1] as $w) {
    $unionSet[json_decode('"' . $w . '"')] = true;
}
$write('stopwords_union.php', $unionSet);

// --- public suffix list -----------------------------------------------------
$rules = [];
foreach (file($psl, FILE_IGNORE_NEW_LINES) as $line) {
    $line = trim($line);
    if ($line === '' || str_starts_with($line, '//')) {
        continue;
    }
    $line = preg_split('/\s/', $line)[0];
    $rule = idn_to_ascii($line, IDNA_DEFAULT, INTL_IDNA_VARIANT_UTS46) ?: $line;
    if (str_starts_with($line, '!')) {
        $rules[substr(idn_to_ascii(substr($line, 1), IDNA_DEFAULT, INTL_IDNA_VARIANT_UTS46) ?: substr($line, 1), 0)] = 2; // exception
    } elseif (str_starts_with($line, '*.')) {
        $base = idn_to_ascii(substr($line, 2), IDNA_DEFAULT, INTL_IDNA_VARIANT_UTS46) ?: substr($line, 2);
        $rules['*.' . $base] = 1; // wildcard
    } else {
        $rules[$rule] = 0;
    }
}
$write('public_suffix.php', $rules);
